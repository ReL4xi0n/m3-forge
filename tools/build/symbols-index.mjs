#!/usr/bin/env node
// Maintainer tool, run in the m3-forge repository only (never by the skill at runtime).
// Builds plugin/skills/material3/scripts/verify/symbols-paths.json: hashes of every official
// Material Symbols path at the default instance (weight 400, grade 0, 24 px; Outlined, Rounded and
// Sharp; unfilled and filled), in both official file forms (symbols/web/**.svg, viewBox
// 0 -960 960 960, and symbols/android/**.xml, viewport 960). The verify icon-source check accepts a
// vector icon only if every path hashes into this set (spec §10: icons come only from the official
// Material Symbols set; owner decision 2026-11-17).
//
// Source: google/material-design-icons at the commit pinned in knowledge/sources.lock.json
// ("material-symbols-paths"), checked out sparsely with:
//   git clone --filter=blob:none --no-checkout --depth 1 https://github.com/google/material-design-icons.git
//   git fetch --depth 1 --filter=blob:none origin <commit>; git sparse-checkout init --no-cone
//   sparse patterns: the six lines in SPARSE below; git checkout <commit>
// Usage: node tools/build/symbols-index.mjs <checkout dir> [--check]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonical, hashOf, normalizePath, INDEX_FILE } from '../../plugin/skills/material3/scripts/verify/symbols.mjs';

export const SPARSE = [
  '/symbols/web/*/*/*_24px.svg', '!/symbols/web/*/*/*_wght*', '!/symbols/web/*/*/*_grad*',
  '/symbols/android/*/*/*_24px.xml', '!/symbols/android/*/*/*_wght*', '!/symbols/android/*/*/*_grad*',
];
const STYLES = ['materialsymbolsoutlined', 'materialsymbolsrounded', 'materialsymbolssharp'];
const HASH_BYTES = 8;

export function pathsOf(file, text) {
  return file.endsWith('.svg')
    ? [...text.matchAll(/<path\b[^>]*\bd="([^"]*)"/g)].map(m => m[1])
    : [...text.matchAll(/android:pathData="([^"]*)"/g)].map(m => m[1]);
}

export function buildIndex(dir) {
  const hashes = new Set();
  const counts = { files: 0, paths: 0, unreadable: 0, icons: 0 };
  for (const [kind, ext] of [['web', '.svg'], ['android', '.xml']]) {
    const base = join(dir, 'symbols', kind);
    const icons = readdirSync(base);
    if (kind === 'web') counts.icons = icons.length;
    for (const icon of icons) {
      for (const style of STYLES) {
        for (const name of [`${icon}_24px${ext}`, `${icon}_fill1_24px${ext}`]) {
          let text;
          try { text = readFileSync(join(base, icon, style, name), 'utf8'); } catch { continue; }
          counts.files++;
          for (const d of pathsOf(name, text)) {
            const abs = normalizePath(d);
            if (!abs) { counts.unreadable++; continue; }
            counts.paths++;
            hashes.add(hashOf(canonical(abs)));
          }
        }
      }
    }
  }
  const sorted = [...hashes].sort();
  return { counts, unique: sorted.length, hashes: Buffer.from(sorted.join(''), 'hex').toString('base64') };
}

function main() {
  const dir = process.argv[2];
  if (!dir) { console.error('usage: node tools/build/symbols-index.mjs <checkout dir> [--check]'); process.exit(2); }
  const repo = resolve(fileURLToPath(import.meta.url), '..', '..', '..');
  const lock = JSON.parse(readFileSync(join(repo, 'knowledge', 'sources.lock.json'), 'utf8')).sources.find(s => s.id === 'material-symbols-paths');
  if (!lock) { console.error('knowledge/sources.lock.json has no "material-symbols-paths" source'); process.exit(2); }
  const r = buildIndex(dir);
  const out = {
    _comment: 'Generated by tools/build/symbols-index.mjs. SHA-256 (first 8 bytes) of the canonical absolute path data of every official Material Symbols path listed under "source". Do not edit by hand.',
    source: { repo: lock.repo, commit: lock.commit, selection: 'symbols/{web,android}/<icon>/materialsymbols{outlined,rounded,sharp}/<icon>{,_fill1}_24px.{svg,xml} (weight 400, grade 0, 24 px)', ...r.counts },
    hashBytes: HASH_BYTES,
    count: r.unique,
    hashes: r.hashes,
  };
  const text = `${JSON.stringify(out, null, 2)}\n`;
  if (process.argv.includes('--check')) {
    const same = readFileSync(INDEX_FILE, 'utf8') === text;
    console.log(same ? 'symbols-paths.json is up to date' : 'symbols-paths.json differs from a fresh build');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(INDEX_FILE, text);
  console.log(JSON.stringify({ ...out.source, unique: r.unique, bytes: text.length }));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
