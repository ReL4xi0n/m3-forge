#!/usr/bin/env node
// Maintainer tool, run in the m3-forge repository only (never by the skill at runtime).
// Reads md.sys.shape.corner.* from the extracted token file and writes shape-scale.json next to
// plugin/skills/material3/scripts/verify/, so the verify checks carry the scale as plain numbers.
// Usage: node tools/build/shape-scale.mjs [path/to/merged.json]  (default: knowledge/tokens/merged.json)
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PREFIX = 'md.sys.shape.corner.';

// merged: the array of token records ({ id, canonical: { dp } ... }).
export function buildShapeScale(merged) {
  const sources = {};
  for (const t of merged) {
    if (!t || typeof t.id !== 'string' || !t.id.startsWith(PREFIX)) continue;
    const dp = t.canonical && t.canonical.dp;
    if (typeof dp === 'number' && Number.isFinite(dp)) sources[t.id] = dp;
  }
  const ids = Object.keys(sources).sort();
  const sorted = Object.fromEntries(ids.map(id => [id, sources[id]]));
  const scale = [...new Set(Object.values(sorted))].sort((a, b) => a - b);
  return {
    _comment:
      'Generated by tools/build/shape-scale.mjs from the numeric dp values of the md.sys.shape.corner.* ' +
      'tokens listed under "sources" (extracted token set, merged.json). Do not edit by hand.',
    sources: sorted,
    scale,
  };
}

if (resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  const input = process.argv[2] || fileURLToPath(new URL("../../knowledge/tokens/merged.json", import.meta.url));
  const merged = JSON.parse(await readFile(input, 'utf8'));
  const out = fileURLToPath(new URL('../../plugin/skills/material3/scripts/verify/shape-scale.json', import.meta.url));
  const data = buildShapeScale(merged);
  await writeFile(out, JSON.stringify(data, null, 2) + '\n');
  console.log(`shape-scale.json: ${data.scale.join(', ')}`);
}
