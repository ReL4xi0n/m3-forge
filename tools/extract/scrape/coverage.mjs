// Coverage: planned pages vs scraped pages, per-component tab coverage, and justified exceptions.
// The rendered report holds only paths, sections, flags, statuses and counts (no page text).

export const EXCEPTION_KINDS = new Set(['robots', 'http-404', 'redirect-out-of-scope', 'duplicate-of', 'owner-excluded']);
const TAB_COLUMNS = ['overview', 'specs', 'guidelines', 'accessibility'];

export function validateExceptions(exceptions) {
  for (const [path, e] of Object.entries(exceptions || {})) {
    if (!e || !EXCEPTION_KINDS.has(e.kind)) throw new Error(`exception for ${path}: unknown kind "${e && e.kind}"`);
    if (typeof e.detail !== 'string' || e.detail.trim().length < 10) {
      throw new Error(`exception for ${path}: detail must be at least 10 characters`);
    }
  }
  return exceptions || {};
}

const componentOf = path => /^\/components\/([^/]+)\/([^/?]+)$/.exec(path);

export function computeCoverage(state, plan, exceptions, { only = null } = {}) {
  const ex = validateExceptions(exceptions);
  const pages = state.pages;
  const onlySet = only ? new Set(only) : null;
  const paths = Object.keys(pages)
    .filter(p => !onlySet || onlySet.has(p) || onlySet.has(pages[p].discoveredFrom))
    .sort();
  const isScraped = p => {
    const s = pages[p];
    if (!s) return false;
    if (s.status === 'done') return true;
    return s.status === 'redirect' && pages[s.finalPath]?.status === 'done';
  };

  const cov = {
    sitemapTotal: plan.sitemapTotal, inScope: paths.length, expressive: { url: 0, content: 0 },
    done: 0, redirects: 0, skippedRobots: 0, failed: 0, missing: [], unjustified: [], jsonNone: [], rows: [], components: [],
  };
  for (const path of paths) {
    const s = pages[path];
    const expressive = s.expressiveUrl ? 'url' : s.expressiveMention ? 'content' : '-';
    if (expressive !== '-') cov.expressive[expressive]++;
    const row = { path, section: s.section ?? null, expressive, status: s.status, json: s.jsonCount ?? 0 };
    if (s.finalPath) row.finalPath = s.finalPath;
    if (s.reason) row.reason = s.reason;
    if (ex[path]) row.exception = ex[path];
    cov.rows.push(row);
    if (s.status === 'done') {
      cov.done++;
      if ((s.flags || []).includes('json-none')) cov.jsonNone.push(path);
    } else if (s.status === 'skipped' && s.reason === 'robots') {
      cov.skippedRobots++;
    } else if (s.status === 'redirect' && isScraped(path)) {
      cov.redirects++;
    } else {
      if (s.status === 'failed') cov.failed++;
      cov.missing.push(path);
      if (!ex[path]) cov.unjustified.push(path);
    }
  }

  const byComponent = new Map();
  for (const path of paths) {
    const m = componentOf(path);
    if (!m) continue;
    const c = byComponent.get(m[1]) || { component: m[1], tabs: new Set(), expanded: 0 };
    c.tabs.add(path);
    for (const t of pages[path].tabLinks || []) if (componentOf(t)?.[1] === m[1]) c.tabs.add(t);
    c.expanded += pages[path].expanded || 0;
    byComponent.set(m[1], c);
  }
  for (const c of [...byComponent.values()].sort((a, b) => a.component.localeCompare(b.component))) {
    const tabsOnSite = [...c.tabs].sort();
    const tabsScraped = tabsOnSite.filter(isScraped);
    cov.components.push({
      component: c.component, tabsOnSite, tabsScraped, missingTabs: tabsOnSite.filter(t => !isScraped(t)), expanded: c.expanded,
    });
  }
  return cov;
}

function cell(c, tabPath, pages) {
  if (!c.tabsOnSite.includes(tabPath)) return '—';
  if (c.tabsScraped.includes(tabPath)) return '✓';
  const s = pages?.[tabPath];
  return `✗ (${s?.reason || s?.status || 'not scraped'})`;
}

export function renderCoverageMd(cov) {
  const pages = Object.fromEntries(cov.rows.map(r => [r.path, r]));
  const out = [];
  out.push('# Site coverage', '');
  out.push('Generated by `tools/extract/scrape/run.mjs coverage`. Paths and statuses only; no page text.', '');
  out.push(`- Sitemap URLs: ${cov.sitemapTotal}`);
  out.push(`- In scope: ${cov.inScope}`);
  out.push(`- Expressive: ${cov.expressive.url} by URL, ${cov.expressive.content} by content`);
  out.push(`- Done: ${cov.done}; redirects to scraped pages: ${cov.redirects}; skipped by robots.txt: ${cov.skippedRobots}`);
  out.push(`- Failed: ${cov.failed}; missing: ${cov.missing.length}; unjustified: ${cov.unjustified.length}`);
  out.push(`- JSON-none pages: ${cov.jsonNone.length}`, '');

  out.push('## Component tabs', '');
  out.push('| component | Overview | Specs | Guidelines | Accessibility | other tabs | expanded elements |');
  out.push('|---|---|---|---|---|---|---|');
  for (const c of cov.components) {
    const base = `/components/${c.component}/`;
    const cells = TAB_COLUMNS.map(t => cell(c, base + t, pages));
    const others = c.tabsOnSite.filter(t => !TAB_COLUMNS.includes(t.slice(base.length)))
      .map(t => `${t.slice(base.length)} ${cell(c, t, pages)}`).join(', ') || '—';
    out.push(`| ${c.component} | ${cells.join(' | ')} | ${others} | ${c.expanded} |`);
  }
  out.push('');

  out.push('## Pages', '');
  out.push('| path | section | expressive | status | JSON | note |');
  out.push('|---|---|---|---|---|---|');
  for (const r of cov.rows) {
    const note = [r.finalPath && `→ ${r.finalPath}`, r.reason, r.exception && `${r.exception.kind}: ${r.exception.detail}`].filter(Boolean).join('; ');
    out.push(`| ${r.path} | ${r.section ?? ''} | ${r.expressive} | ${r.status} | ${r.json} | ${note} |`);
  }
  out.push('');

  out.push('## JSON-none pages', '');
  out.push(...(cov.jsonNone.length ? cov.jsonNone.map(p => `- ${p}`) : ['(none)']), '');
  out.push('## Missing pages', '');
  out.push(...(cov.missing.length
    ? cov.missing.map(p => `- ${p}: ${pages[p].reason || pages[p].status}${pages[p].exception ? ` (justified: ${pages[p].exception.kind})` : ' (UNJUSTIFIED)'}`)
    : ['(none)']), '');
  return out.join('\n');
}
