import test from 'node:test';
import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { verify } from '../index.mjs';
import { STATIC_CHECKS, checkSuite, nonZero, run, sample } from './helpers.mjs';

checkSuite('web', [...STATIC_CHECKS, 'foreign-styling']);

test('web theme: custom properties in theme blocks are allowlisted, not reported', async () => {
  const r = await run('web', 'theme');
  assert.deepEqual(r.violations, []);
  assert.equal(r.exitCode, 0);
  assert.ok(r.allowlisted.length > 0);
  for (const a of r.allowlisted) {
    assert.equal(a.file, 'tokens.css');
    assert.equal(typeof a.line, 'number');
    assert.ok(a.reason.length > 0);
    assert.ok(Object.keys(a.suppressed).length > 0);
  }
  const suppressed = new Set(r.allowlisted.flatMap(a => Object.keys(a.suppressed)));
  for (const c of ['hardcoded-color', 'off-token-type', 'off-token-radius', 'shadow-gradient']) {
    assert.ok(suppressed.has(c), `theme literals for ${c} are listed as allowlisted`);
  }
  // Theme declarations are not counted as UI lines; the rest of both files is.
  assert.equal(r.themeLines, 12);
  assert.ok(r.uiLines > 0);
});

test('web: skipped folders and generated files are not scanned', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'm3-verify-web-'));
  try {
    await cp(sample('web', 'hardcoded-color-clean'), dir, { recursive: true });
    const dirty = '.x { color: #ff0000; padding: 3px; }\n';
    for (const sub of ['node_modules/lib', 'dist', 'build', '.git']) {
      await mkdir(join(dir, sub), { recursive: true });
      await writeFile(join(dir, sub, 'x.css'), dirty);
    }
    await writeFile(join(dir, 'vendor.min.css'), dirty);
    await writeFile(join(dir, 'types.d.ts'), "export const c: string = '#ff0000';\n");
    await writeFile(join(dir, 'gen.js'), `// @generated by a tool\nexport const c = '#ff0000';\n`);
    const r = await verify({ projectDir: dir, platform: 'web' });
    assert.deepEqual(nonZero(r.counts), {});
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('web: bootstrap classes are still foreign in a tailwind project', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'm3-verify-web-'));
  try {
    await cp(sample('web', 'foreign-styling-clean'), dir, { recursive: true });
    await writeFile(join(dir, 'extra.html'), '<button class="btn btn-primary">Go</button>\n');
    const r = await verify({ projectDir: dir, platform: 'web' });
    assert.deepEqual(nonZero(r.counts), { 'foreign-styling': 1 });
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
